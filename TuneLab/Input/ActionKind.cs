namespace TuneLab.Input;

// 一条动作的后果分档。决定命令面（`action run`）的授权处置：见 docs/command-surface.md §5.1。
//
// 【为什么不复用 CommandKind】那是【一条命令】的类别（Read/Edit/Sandbox），标注的是入口安全性；
// 这里分的是【一条动作】的后果轻重。`action run` 作为命令恒是 Edit（它可能写，唯一诚实的声明），
// 具体这一次要不要问用户，由被触发动作的这一档说。
internal enum ActionKind
{
    // 只改应用/编辑器自身的状态：不随工程保存、不进撤销栈、不碰磁盘（播放、切工具、开合面板、缩放…）。
    // **不过闸门**——用户一眼看得见、自己就能改回来，而每次播放都弹一张确认卡片会让动作面根本没法用。
    AppState,

    // 改工程数据、进撤销栈（剪贴板动词、移调、撤销/重做本身）。过闸门，走一问一答：动作没法像脚本那样
    // 先跑一遍预览"会改多少"，但有撤销栈兜底，故不需要更重的档位。
    ProjectEdit,

    // 可能丢掉未保存的工作、或者往磁盘写文件（新建 / 打开 / 保存）。恒过闸门，且措辞要把后果说出来
    // ——撤销栈救不回这一类（同 `project export` 与删脚本恒过闸门的理由）。
    Destructive,
}
